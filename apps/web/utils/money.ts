/**
 * Decimal(10,2) приходит из Prisma СТРОКОЙ, а не числом: «5700.00».
 * Через Number его прогонять нельзя — на суммах выше 2^53 и на дробных
 * тарифах теряется точность, а сверять «моё против серверного» в экране
 * конфликта придётся посимвольно.
 *
 * Поэтому форматируем строку, не превращая её в число.
 */
export function formatMoney(value: string): string {
	const [whole = "0", cents = ""] = value.split(".")
	// Тонкая шпация U+2009 — разряды не слипаются и не разъезжаются
	const grouped = whole.replace(/\B(?=(\d{3})+(?!\d))/g, " ")
	// Копейки печатаем только если они есть: «5 700», а не «5 700,00»
	return /^0*$/.test(cents) ? grouped : `${grouped},${cents}`
}
